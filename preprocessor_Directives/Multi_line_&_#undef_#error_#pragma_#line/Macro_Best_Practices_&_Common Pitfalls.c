#include <stdio.h>

/*=============================================================================
    1. OBJECT-LIKE MACRO (GOOD)
==============================================================================*/

#define BUFFER_SIZE    128

/*-----------------------------------------------------------------------------
    WRONG
    #define BUFFER_SIZE 128;

    Don't put ';' inside macro definitions.
-----------------------------------------------------------------------------*/


/*=============================================================================
    2. ALWAYS PARENTHESIZE PARAMETERS
==============================================================================*/

/* GOOD */
#define SQUARE(x)      ((x) * (x))

/*-----------------------------------------------------------------------------
    WRONG

    #define SQUARE(x) x * x

    SQUARE(2 + 3)

    Expands to

        2 + 3 * 2 + 3

    Result = 11

    Expected = 25
-----------------------------------------------------------------------------*/


/*=============================================================================
    3. PARENTHESIZE ENTIRE EXPRESSION
==============================================================================*/

#define ADD(a,b)       ((a) + (b))

/*-----------------------------------------------------------------------------
    WRONG

    #define ADD(a,b) (a) + (b)

    10 * ADD(2,3)

    becomes

    10 * (2) + (3)

    Result = 23
-----------------------------------------------------------------------------*/


/*=============================================================================
    4. BIT MANIPULATION MACRO
==============================================================================*/

#define BIT(n)         (1U << (n))


/*=============================================================================
    5. REGISTER STYLE MACROS
==============================================================================*/

#define SET_BIT(x,n)     ((x) |= BIT(n))
#define CLEAR_BIT(x,n)   ((x) &= ~BIT(n))
#define TOGGLE_BIT(x,n)  ((x) ^= BIT(n))
#define READ_BIT(x,n)    (((x) >> (n)) & 1U)


/*=============================================================================
    6. ARRAY SIZE MACRO
==============================================================================*/

#define ARRAY_SIZE(arr)   (sizeof(arr)/sizeof((arr)[0]))


/*=============================================================================
    7. MULTI-LINE MACRO (GOOD)
==============================================================================*/

#define PRINT_BOX(msg)                 \
do                                     \
{                                      \
    printf("-------------------\n");   \
    printf("%s\n", msg);               \
    printf("-------------------\n");   \
} while(0)


/*-----------------------------------------------------------------------------
    WRONG

    #define PRINT_BOX(msg)
        printf(...);
        printf(...);

    Always use do{ }while(0)
-----------------------------------------------------------------------------*/


/*=============================================================================
    8. DEBUG MACRO
==============================================================================*/

#define DEBUG_PRINT(msg)               \
do                                     \
{                                      \
    printf("[DEBUG] %s\n", msg);       \
} while(0)


/*=============================================================================
    9. CONSTANT USING const (Preferred for Typed Constants)
==============================================================================*/

const float PI = 3.14159f;


/*=============================================================================
    10. static inline FUNCTION
==============================================================================*/

static inline int square_inline(int x)
{
    return x * x;
}


/*=============================================================================
    MAIN
==============================================================================*/

int main(void)
{
    printf("========== Macro Demo ==========\n\n");

    /*-----------------------------------------------------------
        Object-like Macro
    -----------------------------------------------------------*/
    printf("BUFFER_SIZE = %d\n\n", BUFFER_SIZE);


    /*-----------------------------------------------------------
        Parenthesized Macro
    -----------------------------------------------------------*/
    printf("SQUARE(5) = %d\n", SQUARE(5));
    printf("SQUARE(2+3) = %d\n\n", SQUARE(2+3));


    /*-----------------------------------------------------------
        Full Expression Parentheses
    -----------------------------------------------------------*/
    printf("ADD(20,30) = %d\n", ADD(20,30));
    printf("10 * ADD(2,3) = %d\n\n", 10 * ADD(2,3));


    /*-----------------------------------------------------------
        Bit Macro
    -----------------------------------------------------------*/
    printf("BIT(5) = %u\n\n", BIT(5));


    /*-----------------------------------------------------------
        Register Style Example
    -----------------------------------------------------------*/
    unsigned int reg = 0;

    SET_BIT(reg,3);
    printf("SET_BIT(3)     = %u\n", reg);

    SET_BIT(reg,1);
    printf("SET_BIT(1)     = %u\n", reg);

    CLEAR_BIT(reg,3);
    printf("CLEAR_BIT(3)   = %u\n", reg);

    TOGGLE_BIT(reg,0);
    printf("TOGGLE_BIT(0)  = %u\n", reg);

    printf("READ_BIT(1)    = %u\n\n", READ_BIT(reg,1));


    /*-----------------------------------------------------------
        Array Size
    -----------------------------------------------------------*/
    int arr[10];

    printf("Array Size = %zu\n\n", ARRAY_SIZE(arr));


    /*-----------------------------------------------------------
        Multi-line Macro
    -----------------------------------------------------------*/
    PRINT_BOX("Embedded Firmware");


    /*-----------------------------------------------------------
        Debug Macro
    -----------------------------------------------------------*/
    DEBUG_PRINT("UART Initialized");


    /*-----------------------------------------------------------
        const Example
    -----------------------------------------------------------*/
    printf("\nPI = %.5f\n", PI);


    /*-----------------------------------------------------------
        static inline Example
    -----------------------------------------------------------*/
    printf("square_inline(7) = %d\n\n", square_inline(7));


    /*-----------------------------------------------------------
        DON'T DO THIS
    -----------------------------------------------------------*/

    /*
        int i = 5;
        int j = 8;

        MAX(i++, j++);

        Bad Practice

        Macro arguments having ++ or -- can be evaluated
        multiple times.
    */


    /*
        #define PI 3.14;

        Wrong

        float x = PI;

        Expands to

        float x = 3.14;;
    */


    /*
        #define MUL(a,b) a*b

        Wrong

        10 * MUL(2,3)

        becomes

        10 * 2 * 3
    */


    /*
        #define TEST()

        printf("A");

        printf("B");

        Wrong Multi-line Macro
    */


    printf("Demo Completed\n");

    return 0;
}